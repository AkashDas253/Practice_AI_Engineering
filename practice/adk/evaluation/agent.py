import json
from pathlib import Path
from dotenv import load_dotenv
from google.adk import Agent

# Load GEMINI_API_KEY from root .env
env_path = Path(__file__).resolve().parent.parent / ".env"
load_dotenv(dotenv_path=env_path)

# Specify model
MODEL_ID = "gemini-3.5-flash-lite"

# Module-isolated output directory inside evaluation/ folder
LOCAL_OUTPUT_DIR = Path(__file__).resolve().parent / "output"
LOCAL_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
EVAL_FILE = LOCAL_OUTPUT_DIR / "eval_results.json"


def _load_eval_store() -> dict:
    if EVAL_FILE.exists():
        try:
            return json.loads(EVAL_FILE.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            return {}
    return {}


def _save_eval_store(store: dict) -> None:
    EVAL_FILE.write_text(json.dumps(store, indent=2), encoding="utf-8")


def evaluate_test_case(test_id: str, prompt: str, output: str, passed: bool, notes: str) -> str:
    """Evaluates and records an agent reasoning or tool execution test result.

    Args:
        test_id: Unique identifier for the test case (e.g., 'test_01_math').
        prompt: The input prompt given to the evaluated agent.
        output: The actual output generated by the agent.
        passed: Whether the response met the evaluation criteria (True/False).
        notes: Feedback explaining the evaluation verdict.
    """
    store = _load_eval_store()
    store[test_id] = {
        "prompt": prompt,
        "output": output,
        "passed": passed,
        "notes": notes
    }
    _save_eval_store(store)
    status = "PASSED" if passed else "FAILED"
    return f"Evaluation recorded for '{test_id}': Status = {status}."


def list_evaluations() -> str:
    """Lists all recorded evaluation suite results stored on disk."""
    store = _load_eval_store()
    if not store:
        return "No evaluation records found."
    formatted = []
    for tid, data in store.items():
        status = "PASSED" if data["passed"] else "FAILED"
        formatted.append(f"- [{tid}] Status: {status} | Notes: {data['notes']}")
    return "Recorded Evaluation Suite Results:\n" + "\n".join(formatted)


root_agent = Agent(
    name="evaluation_agent",
    model=MODEL_ID,
    instruction=(
        "You are an automated evaluation agent that assesses agent reasoning, tool calls, and response quality.\n"
        "Use `evaluate_test_case` to log pass/fail status and notes for given test prompts and responses.\n"
        "Use `list_evaluations` to view current test metrics stored on disk."
    ),
    tools=[evaluate_test_case, list_evaluations],
    description="Agent for testing and evaluating model reasoning and tool output accuracy.",
)